// ─── Error helpers ───────────────────────────────────────────────────────────

export function extractErrorMessage(err: unknown): string {
  if (err instanceof ApiResponseError) {
    const { data } = err;

    const fieldErrors = Object.entries(data)
      .filter(([key]) => key !== "detail")
      .flatMap(([, messages]) =>
        Array.isArray(messages) ? messages : [messages]
      )
      .filter(Boolean)
      .join(" ");

    if (fieldErrors) {
      return fieldErrors;
    }

    if (data.detail) {
      return data.detail;
    }
  }

  if (err instanceof Error) {
    return err.message;
  }

  return "An unexpected error occurred. Please try again.";
}

// ─── Gmail endpoints ─────────────────────────────────────────────────────────

export async function listGmailMessages(
  params: GmailListParams = {}
): Promise<GmailMessageListResponse> {
  const query = new URLSearchParams();

  if (params.max_results) {
    query.set("max_results", String(params.max_results));
  }

  if (params.page_token) {
    query.set("page_token", params.page_token);
  }

  const queryString = query.toString()
    ? `?${query.toString()}`
    : "";

  return apiFetch<GmailMessageListResponse>(
    `/api/gmail/messages/${queryString}`
  );
}

export async function getGmailMessage(
  messageId: string
): Promise<GmailMessage> {
  return apiFetch<GmailMessage>(
    `/api/gmail/messages/${messageId}/`
  );
}

export async function searchGmailMessages(
  params: GmailSearchParams
): Promise<GmailMessageListResponse> {
  const query = new URLSearchParams({
    q: params.q,
  });

  if (params.max_results) {
    query.set("max_results", String(params.max_results));
  }

  if (params.page_token) {
    query.set("page_token", params.page_token);
  }

  return apiFetch<GmailMessageListResponse>(
    `/api/gmail/search/?${query.toString()}`
  );
}

