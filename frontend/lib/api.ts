// ─── Base config ─────────────────────────────────────────────────────────────

const BASE_URL = (
  import.meta.env.VITE_API_BASE_URL ?? "http://127.0.0.1:8000"
).replace(/\/$/, "");

// ─── Error class ──────────────────────────────────────────────────────────────

export class ApiResponseError extends Error {
  status: number;
  data: ApiError;

  constructor(status: number, data: ApiError) {
    super(data.detail ?? `Request failed with status ${status}`);
    this.name = "ApiResponseError";
    this.status = status;
    this.data = data;
  }
}

// ─── Core fetch wrapper ───────────────────────────────────────────────────────

async function apiFetch<T>(
  path: string,
  options: RequestInit = {}
): Promise<T> {
  const url = `${BASE_URL}${path}`;

  // These endpoints must be accessible without an existing JWT.
  // In particular, Google OAuth initiation must remain public.
  const isPublicAuthEndpoint =
    path === "/api/auth/google/" ||
    path === "/api/auth/login/" ||
    path === "/api/auth/register/";

  const token =
    !isPublicAuthEndpoint && typeof window !== "undefined"
      ? localStorage.getItem("access_token")
      : null;

  const headers = new Headers(options.headers);

  // Only send Content-Type when the request has a body.
  // This prevents unnecessary CORS preflight requests for GET endpoints.
  if (options.body && !headers.has("Content-Type")) {
    headers.set("Content-Type", "application/json");
  }

  if (!headers.has("Accept")) {
    headers.set("Accept", "application/json");
  }

  if (token) {
    headers.set("Authorization", `Bearer ${token}`);
  }

  const res = await fetch(url, {
    ...options,
    headers,
  });

  let data: unknown;

  try {
    data = await res.json();
  } catch {
    data = {};
  }

  if (!res.ok) {
    throw new ApiResponseError(
      res.status,
      data as ApiError
    );
  }

  return data as T;
}

