/**
 * POST /api/auth/login/
 */
export async function login(
  payload: LoginRequest
): Promise<LoginResponse> {
  return apiFetch<LoginResponse>("/api/auth/login/", {
    method: "POST",
    body: JSON.stringify(payload),
  });
}

