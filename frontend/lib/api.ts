// ─── Base config ─────────────────────────────────────────────────────────────

const BASE_URL =
  process.env.NEXT_PUBLIC_API_BASE_URL?.replace(/\/$/, "") ??
  "http://localhost:8000";

// ─── Error class ──────────────────────────────────────────────────────────────

export class ApiResponseError extends Error {
  status: number;
  data: ApiError;

  constructor(status: number, data: ApiError) {
    super(data.detail ?? `Request failed with status ${status}`);
    this.name = "ApiResponseError";
    this.status = status;
    this.data = data;
  }
}

// ─── Core fetch wrapper ───────────────────────────────────────────────────────

async function apiFetch<T>(
  path: string,
  options: RequestInit = {}
): Promise<T> {
  const url = `${BASE_URL}${path}`;

  const token =
    typeof window !== "undefined"
      ? localStorage.getItem("access_token")
      : null;

  /*
   * Use the Headers API instead of spreading options.headers.
   *
   * RequestInit.headers can be Headers, an array, or an object.
   * new Headers() safely handles all of those forms.
   */
  const headers = new Headers(options.headers);

  if (!headers.has("Content-Type")) {
    headers.set("Content-Type", "application/json");
  }

  if (!headers.has("Accept")) {
    headers.set("Accept", "application/json");
  }

  if (token) {
    headers.set("Authorization", `Bearer ${token}`);
  }

  const res = await fetch(url, {
    ...options,
    headers,
  });

  // Parse JSON even on error responses.
  let data: unknown;

  try {
    data = await res.json();
  } catch {
    data = {};
  }

  if (!res.ok) {
    throw new ApiResponseError(res.status, data as ApiError);
  }

  return data as T;
}

// ─── Auth endpoints ──────────────────────────────────────────────────────────

/**
 * POST /api/auth/login/
 *
 * Authenticates a user with email + password.
 * Returns access/refresh tokens and the user object.
 */
export async function login(
  payload: LoginRequest
): Promise<LoginResponse> {
  return apiFetch<LoginResponse>("/api/auth/login/", {
    method: "POST",
    body: JSON.stringify(payload),
  });
}

